() => {
  const results = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const reset = (site = 0) => {
    if ($('dialog').open) $('dialog').close();
    game = makeGame(42); game.started = true; paused = true; keys.clear();
    const t = tileAt(game.sites[site].x, game.sites[site].y);
    t.visible = true; chooseSite(site); Object.assign(game.hero, center(t));
  };
  const test = (name, run) => { try { reset(); run(); results.push({ name, pass: true }); } catch (e) { results.push({ name, pass: false, error: e.message }); } };
  const bags = ['gold', 'material', 'food', 'rare'];
  const balanced = book => bags.every(key => book.income[key] - book.expense[key] === book.end[key] - book.start[key]);
  const fastClear = () => {
    check(game.phase === 'day', '只能从白天进入夜战');
    startNight();
    let guard = 0;
    while (game.phase === 'night' && guard++ < 5000) {
      for (const enemy of game.enemies) if (enemy.hp > 0) damageEnemy(enemy, 100000);
      advanceBattle(0.2);
    }
    check(guard < 5000, '清场超时，阶段 ' + game.phase);
  };
  const ownedFarm = () => game.tiles.find(t => t.owned && t.node?.kind === 'farm');
  test('四角评分避开重叠更大的候选', () => {
    const blocks = [{ x: 0, y: 0, w: 80, h: 80 }];
    const candidates = [
      { x: 0, y: 0, w: 50, h: 50 }, { x: 200, y: 0, w: 50, h: 50 },
      { x: 0, y: 200, w: 50, h: 50 }, { x: 200, y: 200, w: 50, h: 50 }
    ];
    check(pickLeastOverlap(candidates, blocks) === 1, '应选中没有重叠的候选');
  });
  test('分夜收支闭合且早期记录不被后续夜改写', () => {
    const farm = ownedFarm();
    check(farm, '起始圈应有农田');
    develop(farm);
    fastClear();
    check(game.phase === 'day' && game.day === 2, '第 1 夜应天亮');
    const first = game.ledger[1];
    check(first.closed && first.dawned && !first.boss, '第 1 夜应作为普通夜关闭');
    check(balanced(first), '第 1 夜收入减支出不等于期末减期初');
    check(first.expense.material === 2 && first.income.food === 3, '开发支出或农田产出没有记到第 1 夜');
    check(first.income.gold === first.kills && first.kills > 0, '击杀金币和击杀数不一致');
    check(!game.ledger[3], '未经历的第 3 夜不应造记录');
    check(game.ledger[2] && !game.ledger[2].closed, '第 2 夜开始后尚未结束');
    const snap = JSON.stringify(first);
    fastClear();
    check(JSON.stringify(game.ledger[1]) === snap, '第 2 夜改写了第 1 夜');
    check(game.day === 3 && balanced(game.ledger[2]), '第 2 夜账目不闭合');
    check(game.ledger[1].end.gold !== game.ledger[2].end.gold || game.ledger[1].expense.material !== game.ledger[2].expense.material, '两夜账目没有分开');
    check(game.ledger[2].start.gold === game.ledger[1].end.gold && game.ledger[2].start.food === game.ledger[1].end.food, '下一夜起点应等于上一夜终点');
  });
  test('提前召唤显示真实夜次、库存和独立分夜', () => {
    develop(ownedFarm());
    fastClear(); fastClear();
    check(game.day === 3, '应来到第 3 天');
    const early = JSON.stringify(game.ledger[1]);
    game.scheduled = true; game.early = true;
    fastClear();
    check(game.phase === 'won' && game.day === 3, '应在第 3 夜胜利');
    check(JSON.stringify(game.ledger[1]) === early, '胜利结算改写了第 1 夜');
    const boss = game.ledger[3];
    check(boss.closed && boss.boss && boss.early && !boss.dawned, '首领夜不应做天亮结算');
    check(balanced(boss), '首领夜账目不闭合');
    check(!game.ledger[4] && !game.ledger[5], '未打的夜次不应有记录');
    const text = $('victoryCore').innerText;
    check(text.includes('第 3 夜通关'), text);
    check(text.includes('本局击退敌军：' + game.kills + ' 名'), text);
    check(text.includes('城堡剩余耐久 ' + Math.ceil(game.castleHp) + ' / ' + game.castleMax), text);
    check(text.includes('战后库存：金币' + game.resources.gold + '｜材料' + game.resources.material + '｜粮食' + game.resources.food), text);
    check(!document.body.innerText.includes('下局敌军基数') && !document.body.innerText.includes('迎来天亮获得收益'), '出现了禁止的结算文案');
    const buttons = [...$('victoryNights').querySelectorAll('button')];
    check(buttons.map(button => button.textContent).join() === '第1夜,第2夜,第3夜', buttons.map(button => button.textContent).join());
    check($('victoryNights').querySelector('[aria-selected="true"]').textContent === '第3夜', '默认夜次不是实际首领战');
    $('victoryDetail').click();
    check($('victoryDetail').getAttribute('aria-expanded') === 'true' && $('victoryReport').getAttribute('aria-expanded') === 'false', '详情没有独占展开');
    check($('victoryPanel').innerText.includes('本夜没有天亮结算'), $('victoryPanel').innerText);
    check($('victoryPanel').innerText.includes('金币' + boss.end.gold), '详情没有显示这一夜的终点');
    const nightButton = button => [...$('victoryNights').querySelectorAll('button')].find(item => item.textContent === button);
    nightButton('第1夜').click();
    check($('victoryNightLine').innerText.includes('击退 ' + game.ledger[1].kills + ' 名'), $('victoryNightLine').innerText);
    check($('victoryPanel').innerText.includes('金币' + game.ledger[1].start.gold) && $('victoryPanel').innerText.includes('金币' + game.ledger[1].end.gold), '第 1 夜详情不是自己的起终点');
    check(game.ledger[1].end.gold !== game.resources.gold, '第 1 夜终点被写成了战后总库存');
    check($('victoryCore').innerText.includes('本局击退敌军：' + game.kills + ' 名'), '切换夜次后总局击杀被改掉');
    $('victoryReport').click();
    check($('victoryDetail').getAttribute('aria-expanded') === 'false' && $('victoryReport').getAttribute('aria-expanded') === 'true', '战报没有替换详情');
    check($('victoryPanel').innerText.includes('击退 ' + game.ledger[1].kills + ' 名') && !$('victoryPanel').innerText.includes('迎来天亮获得收益'), $('victoryPanel').innerText);
    $('victoryReport').click();
    check($('victoryPanel').hidden && $('victoryReport').getAttribute('aria-expanded') === 'false', '再次点击没有收起');
    check(getComputedStyle(document.querySelector('.side')).display === 'none', '胜利时侧栏仍在');
    check(getComputedStyle(document.querySelector('.status')).display === 'none', '胜利时顶部库存仍在');
    check(getComputedStyle(document.querySelector('.legend')).display === 'none', '常驻图例仍在');
    check(getComputedStyle($('commandBar')).display === 'none', '建造栏仍在');
    const card = $('victoryCard').getBoundingClientRect();
    check(card.width <= innerWidth - 8 && card.right <= innerWidth + 1 && card.bottom <= innerHeight + 1, '结算卡超出视口');
    $('victoryGear').click();
    check(!$('victoryMenu').hidden && $('victoryPause').disabled && $('victoryGear').getAttribute('aria-expanded') === 'true', '齿轮菜单不可用');
    $('victoryMenuClose').click();
    check($('victoryMenu').hidden, '菜单不能关闭');
    $('victoryLegendBtn').click();
    check(!$('victoryLegend').hidden, '图例不能打开');
    $('victoryLegendClose').click();
    check($('victoryLegend').hidden, '图例不能关闭');
  });
  test('城堡损伤、维修、毁墙、失守和居民按实际事件记账', () => {
    const wall = game.tiles.find(t => t.owned && !t.node && !t.building && t !== game.castle && t.ground !== 'water' &&
      Math.max(Math.abs(t.x - game.castle.x), Math.abs(t.y - game.castle.y)) >= 2);
    check(wall, '应有可建墙的领地');
    build(wall, 'wall');
    wall.building.hp = 1;
    for (const t of game.tiles) t.visible = true;
    const camp = createCamp(tileAt(15, 5));
    check(camp, '测试营地应可建');
    const resident = game.residents[0];
    resident.role = 'miner'; resident.camp = camp.id;
    Object.assign(resident, center(campTile(camp)));
    postResident(resident, camp);
    startNight();
    advanceBattle(0.5);
    const enemy = game.enemies.find(item => item.hp > 0);
    check(enemy, '夜战应刷出敌人');
    const castle = center(game.castle);
    game.hero.x = castle.x + 4; game.hero.y = castle.y + 4;
    enemy.x = castle.x; enemy.y = castle.y; enemy.cooldown = 0;
    const before = game.castleHp;
    moveEnemy(enemy, 0.05);
    const dealt = before - game.castleHp;
    check(dealt > 0 && game.ledger[1].castleDamage === dealt, '城堡受伤没有按实际伤害记账');
    const hurt = game.castleHp;
    repair(game.castle);
    check(game.ledger[1].castleRepair === game.castleHp - hurt, '维修应按实际恢复记账');
    check(game.ledger[1].castleDamage === dealt, '维修把已发生的受伤抹掉了');
    game.hero.x = 0.5; game.hero.y = 19.5;
    enemy.cooldown = 0; enemy.next = wall;
    enemy.x = wall.x + 0.8; enemy.y = wall.y + 0.5;
    moveEnemy(enemy, 0.05);
    check(!wall.building && game.ledger[1].buildingsLost === 1, '城墙被毁没有记账');
    loseCamp(camp, null);
    check(game.ledger[1].campsLost.includes(camp.number), '营地失守没有记账');
    check(game.ledger[1].hurt + game.ledger[1].dead >= 1, '居民伤亡没有记账');
  });
  test('胜利地图可平移和只读查看，卡片拖动后不跳', () => {
    const secret = game.tiles.find(t => t.node && Math.abs(t.x - game.castle.x) > 8);
    for (const t of game.tiles) t.visible = true;
    const camp = createCamp(tileAt(15, 5));
    check(camp, '战后应能查看刚建成的营地');
    secret.visible = false;
    game.scheduled = true; game.early = true;
    fastClear();
    check(game.phase === 'won', '第 1 夜提前召唤应能胜利');
    check($('board').scrollWidth > $('board').clientWidth + 20, '地图没有留出可平移范围');
    placeVictoryCard();
    const board = $('board'), before = board.scrollLeft;
    const cardBefore = $('victoryCard').getBoundingClientRect().left;
    canvas.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, clientX: 240, clientY: 220, pointerId: 7, button: 0 }));
    canvas.dispatchEvent(new PointerEvent('pointermove', { bubbles: true, clientX: 70, clientY: 220, pointerId: 7, button: 0 }));
    canvas.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, clientX: 70, clientY: 220, pointerId: 7, button: 0 }));
    check(board.scrollLeft > before + 20, '拖动没有平移地图');
    check(Math.abs($('victoryCard').getBoundingClientRect().left - cardBefore) < 1, '地图平移时结算卡跟着动了');
    $('victoryInspect').hidden = true;
    canvas.dispatchEvent(new MouseEvent('click', { bubbles: true, clientX: 70, clientY: 220 }));
    check($('victoryInspect').hidden, '拖动结束误打开了地点');
    const farm = ownedFarm();
    const hidden = secret;
    const gold = game.resources.gold, hx = game.hero.x, hy = game.hero.y, goal = game.hero.goal;
    mapClick(hidden);
    check(!hidden.visible && $('victoryInspect').hidden, '未探明资源被打开或点亮');
    mapClick(farm);
    check(!$('victoryInspect').hidden && $('victoryPlaceBody').innerText.includes('只读'), $('victoryPlaceBody').innerText);
    check($('victoryInspect').querySelectorAll('button').length === 1, '地点详情出现了操作按钮');
    mapClick(game.castle);
    check($('victoryPlaceTitle').innerText === '城堡', '城堡详情没有打开');
    const campTile = game.tiles.find(t => campCore(t));
    if (campTile) { campTile.visible = true; mapClick(campTile); check($('victoryPlaceBody').innerText.includes('只读'), '营地详情不是只读'); }
    check(game.resources.gold === gold && game.hero.x === hx && game.hero.y === hy && game.hero.goal === goal, '只读查看改变了资源或领主');
    $('victoryCard').style.left = '8px';
    $('victoryCard').style.top = '70px';
    game.victoryUi.userMoved = true;
    game.victoryUi.placed = true;
    const handle = $('victoryHandle');
    const start = $('victoryCard').getBoundingClientRect();
    handle.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, clientX: start.left + 24, clientY: start.top + 12, pointerId: 8, button: 0 }));
    window.dispatchEvent(new PointerEvent('pointermove', { bubbles: true, clientX: start.left + 24, clientY: start.top + 62, pointerId: 8, button: 0 }));
    window.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, clientX: start.left + 24, clientY: start.top + 62, pointerId: 8, button: 0 }));
    const moved = $('victoryCard').getBoundingClientRect();
    check(Math.abs(moved.top - (start.top + 50)) < 2 && game.victoryUi.userMoved,
      '结算卡没有跟着标题拖动 ' + start.top + ' -> ' + moved.top + ' 高' + $('victoryCard').offsetHeight);
    placeVictoryCard();
    check(Math.abs($('victoryCard').getBoundingClientRect().top - moved.top) < 2, '再次布局把玩家拖过的卡片跳走了');
    $('victoryCard').style.left = (innerWidth + 400) + 'px';
    clampVictoryCard();
    check($('victoryCard').getBoundingClientRect().right <= innerWidth + 1, '收缩视口后卡片没有回到视口内');
    check(game.victoryUi.userMoved, '约束视口时丢掉了手动位置');
  });
  test('重开清除结算状态且下一局不继承', () => {
    game.hard = true; game.autoAttack = true;
    game.scheduled = true; game.early = true;
    fastClear();
    check(game.phase === 'won' && game.kills > 0, '应先取得一局胜利');
    game.ledger[game.day].campsLost.push('上局标记');
    game.victoryUi.userMoved = true;
    game.victoryUi.panel = 'detail';
    const oldKills = game.kills;
    newRun();
    check(game.phase === 'day' && !document.body.classList.contains('victory') && $('victoryHud').hidden, '重开后仍停留在结算布局');
    check(game.hard && game.autoAttack && !paused, '重开丢失难度、自动攻击或仍暂停');
    paused = true;
    check(game.kills === 0 && !game.ledger[1].closed && !game.ledger[1].bossGate, '新局继承了上一局进度');
    check(!JSON.stringify(game.ledger).includes('上局标记'), '新局继承了上一局标记');
    check(!game.victoryUi, '新局还留着上一局的拖动和折叠状态');
    tileAt(game.sites[0].x, game.sites[0].y).visible = true;
    chooseSite(0);
    game.scheduled = true; game.early = true;
    fastClear();
    check(game.phase === 'won', '重开后的首领战没有胜利');
    check(closedNights().join() === '1', '第二局混入了上一局的夜次 ' + closedNights().join());
    check(game.kills !== oldKills + game.kills, '第二局击杀数把上一局也加了进去');
    check(!JSON.stringify(game.ledger).includes('上局标记'), '第二局胜利又出现了上一局标记');
    const sum = closedNights().reduce((total, day) => total + game.ledger[day].kills, 0);
    check(sum === game.kills, '分夜击杀之和不等于本局击杀');
    check($('victoryCore').innerText.includes('本局击退敌军：' + game.kills + ' 名'), '第二局结算没有使用新的击杀数');
  });
  reset(); paused = true; sync();
  return { total: results.length, passed: results.filter(item => item.pass).length, results };
}
